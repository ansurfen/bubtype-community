const DICTS: Record<string, Dict> = {
  "zh-CN": zhCN,
  en,
  "zh-TW": zhTW,
  ja,
  vi,
  id,
};

export function normalizeLocale(raw: string | null | undefined): LocaleCode {
  const value = (raw || "zh-CN").trim();
  if (value in DICTS) return value as LocaleCode;
  if (value.toLowerCase().startsWith("zh")) return value.toLowerCase().includes("tw") ? "zh-TW" : "zh-CN";
  if (value.toLowerCase().startsWith("en")) return "en";
  if (value.toLowerCase().startsWith("ja")) return "ja";
  if (value.toLowerCase().startsWith("vi")) return "vi";
  if (value.toLowerCase().startsWith("id")) return "id";
  return "zh-CN";
}

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

export function createT(locale: string): TFn {
  const code = normalizeLocale(locale);
  const primary = DICTS[code] ?? zhCN;
  return (key, vars) => {
    let text = primary[key] ?? zhCN[key] ?? en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}
